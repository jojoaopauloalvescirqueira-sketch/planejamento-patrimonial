'use strict';
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'..'),sourcePath=path.join(root,'src/site'),distPath=path.join(root,'dist');
function incomplete(name){console.error('Pacote de projeto incompleto: falta '+name+'. Inclua os fontes src/site. A pasta dist é gerada por npm run build.');process.exit(1);}
function canonicalIndex(text){return text.replace(/((?:src|href)="(?:assets\/[^"?]+|favicon\.svg))(?:\?v=[a-f0-9]{16})?("\s*\/?>|"\s)/g,'$1$2');}
if(!fs.existsSync(path.join(sourcePath,'index.html')))incomplete('src/site/index.html');
if(!fs.existsSync(path.join(sourcePath,'assets')))incomplete('src/site/assets');
function walk(dir){return fs.readdirSync(dir,{withFileTypes:true}).filter(e=>e.name!=='.DS_Store'&&!e.name.startsWith('._')).flatMap(e=>{
  const file=path.join(dir,e.name);if(e.isSymbolicLink())throw Error('Link simbólico não permitido nos fontes: '+file);
  if(e.isDirectory())return walk(file);if(!e.isFile())throw Error('Fonte não é arquivo regular: '+file);return [file];
});}
const files=walk(sourcePath).filter(p=>path.relative(sourcePath,p)!==path.join('assets','version.js')).sort();
const relative=p=>path.relative(sourcePath,p).split(path.sep).join('/'),sourceIndex=path.join(sourcePath,'index.html'),index=canonicalIndex(fs.readFileSync(sourceIndex,'utf8'));
for(const [,url] of index.matchAll(/(?:src|href)="((?:assets\/|favicon)[^"?]+)(?:\?[^\"]*)?"/g)){
  if(url==='assets/version.js')continue;
  const file=path.resolve(sourcePath,url);if(!file.startsWith(sourcePath+path.sep)||!files.includes(file))incomplete('src/site/'+url);
}
// Keep the existing public-file hash contract, independently of source layout.
const hash=crypto.createHash('sha256').update('asset-query-v1\0');
for(const file of files)hash.update('dist/'+relative(file)+'\0').update(file===sourceIndex?index:fs.readFileSync(file));
const id=hash.digest('hex').slice(0,16),html=index.replace(/((?:src|href)="(?:assets\/[^"?]+|favicon\.svg))(")/g,'$1?v='+id+'$2');
// Finish a complete output before replacing any previous generated directory.
const outputs=path.join(root,'outputs');fs.mkdirSync(outputs,{recursive:true});
const stage=fs.mkdtempSync(path.join(outputs,'.site-build-')),next=path.join(stage,'next'),previous=path.join(stage,'previous');let preserve=false,movedPrevious=false;
try{
  for(const file of files){const target=path.join(next,relative(file));fs.mkdirSync(path.dirname(target),{recursive:true});fs.copyFileSync(file,target);}
  fs.writeFileSync(path.join(next,'index.html'),html);fs.writeFileSync(path.join(next,'assets/version.js'),`// Generated by tools/build.js\nvar PP_BUILD=${JSON.stringify(id)};\n`);
  if(fs.existsSync(distPath)){
    if(fs.lstatSync(distPath).isSymbolicLink())throw Error('A saída dist não pode ser link simbólico.');
    fs.renameSync(distPath,previous);movedPrevious=true;
  }
  try{fs.renameSync(next,distPath);}catch(error){
    if(movedPrevious){try{fs.renameSync(previous,distPath);}catch(restore){preserve=true;throw Error('Falha ao substituir dist. Saída anterior preservada em '+previous+': '+restore.message);}}
    throw error;
  }
}finally{if(!preserve)fs.rmSync(stage,{recursive:true,force:true});}
console.log('SOURCE src/site -> dist ('+files.length+' arquivos-fonte)');console.log('BUILD',id);
